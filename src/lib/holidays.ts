const KNOWN_YEARS = new Set(['2026', '2027']);

export function holidayName(key: string): string | null {
  if (HOLIDAYS[key]) return HOLIDAYS[key];
  if (KNOWN_YEARS.has(key.slice(0, 4))) return null;
  return FIXED[key.slice(5)] ?? null;
}

export function isHoliday(key: string): boolean {
  return holidayName(key) != null;
}
